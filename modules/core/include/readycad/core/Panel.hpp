#pragma once

#include "readycad/core/Aabb.hpp"
#include "readycad/core/Material.hpp"
#include "readycad/core/PanelShape.hpp"

#include <array>
#include <utility>
#include <vector>

namespace rc::core {

enum class FastenerType { Confirmat, Dowel, Eccentric, ShelfSupport, Hinge, Groove, Handle };

/// Which surface of the panel a hole is drilled into.
enum class PanelFace { Top, Bottom, EdgeL1, EdgeL2, EdgeW1, EdgeW2 };

/// One hole. Position is the centre of the hole's entry on the panel surface, in panel
/// coordinates: x along length, y along width, z across thickness (0 on the Bottom face,
/// thickness on the Top face). The hole goes from there into the panel, perpendicular to `face`.
/// Generated by the detailing module (stage 4).
struct Drilling {
    FastenerType fastener = FastenerType::Dowel;
    PanelFace face = PanelFace::Top;
    Vec3 position{0.0};
    Real diameter = 0.0;
    Real depth = 0.0;

    [[nodiscard]] bool isFaceHole() const noexcept
    {
        return face == PanelFace::Top || face == PanelFace::Bottom;
    }
};

/// A straight groove milled into a face (e.g. for the back panel). start/end are the centre
/// line in panel x/y coordinates.
struct Groove {
    PanelFace face = PanelFace::Top;
    Vec2 start{0.0};
    Vec2 end{0.0};
    Real width = 0.0;
    Real depth = 0.0;
};

/// A physical part cut from sheet material (ЛДСП/МДФ/ХДФ) — pure data.
///
/// It does not know where it stands in the furniture: its owning FurnitureComponent computes the
/// geometry and calls fitTo(). Detailing, nesting, export and CAM read panels and never need
/// the component tree.
///
/// Sizes:
///  * finish (чистовой) — the final part with edge banding glued on (what the designer draws);
///  * cut (пильный)     — what the saw cuts: finish minus the edge band thickness.
///    Stage 4 adds pre-milling allowances on top of that.
class Panel {
public:
    /// thicknessAxis — world axis across the panel; lengthAxis — world axis along its length
    /// (and along the grain when the material has one). The two must differ.
    Panel(Material material, Axis thicknessAxis, Axis lengthAxis);

    /// Takes finish length/width from a box in product coordinates.
    void fitTo(const Aabb& box);

    [[nodiscard]] const Material& material() const noexcept { return material_; }
    void setMaterial(Material material) { material_ = std::move(material); }

    [[nodiscard]] Axis thicknessAxis() const noexcept { return thicknessAxis_; }
    [[nodiscard]] Axis lengthAxis() const noexcept { return lengthAxis_; }
    [[nodiscard]] Axis widthAxis() const noexcept;

    [[nodiscard]] Real finishLength() const noexcept { return finishLength_; }
    [[nodiscard]] Real finishWidth() const noexcept { return finishWidth_; }
    [[nodiscard]] Real thickness() const noexcept { return material_.thickness; }

    [[nodiscard]] Real cutLength() const noexcept;
    [[nodiscard]] Real cutWidth() const noexcept;

    [[nodiscard]] const EdgeBand& edge(EdgeSide side) const noexcept;
    void setEdge(EdgeSide side, EdgeBand band);
    [[nodiscard]] const std::array<EdgeBand, 4>& edges() const noexcept { return edges_; }

    [[nodiscard]] const std::vector<Drilling>& drillings() const noexcept { return drillings_; }
    [[nodiscard]] std::vector<Drilling>& drillings() noexcept { return drillings_; }
    void addDrilling(const Drilling& drilling) { drillings_.push_back(drilling); }
    void clearDrillings() noexcept { drillings_.clear(); }

    [[nodiscard]] const std::vector<Groove>& grooves() const noexcept { return grooves_; }
    void addGroove(const Groove& groove) { grooves_.push_back(groove); }

    /// Removes all drillings and grooves (they are derived data: geometry changed -> redo).
    void clearMachining() noexcept
    {
        drillings_.clear();
        grooves_.clear();
    }

    /// The shape: features the user asked for (notches, rounded corners, openings) plus openings
    /// the part gets from elsewhere (a worktop's sink). Part of the part, set by its component
    /// after fitTo(), not of the drilling: clearMachining() keeps it.
    void setShape(std::vector<ShapeFeature> features, std::vector<PanelCutout> automaticOpenings);
    [[nodiscard]] const std::vector<ShapeFeature>& shape() const noexcept { return shape_; }
    /// The finished outline when a feature changes it; empty for a plain rectangle.
    [[nodiscard]] const std::vector<OutlineSide>& outline() const noexcept { return outline_; }
    /// All openings through the panel: the automatic ones and those of the features.
    [[nodiscard]] const std::vector<PanelCutout>& cutouts() const noexcept { return cutouts_; }

private:
    Material material_;
    Axis thicknessAxis_;
    Axis lengthAxis_;
    Real finishLength_ = 0.0;
    Real finishWidth_ = 0.0;
    std::array<EdgeBand, 4> edges_{};
    std::vector<Drilling> drillings_;
    std::vector<Groove> grooves_;
    std::vector<ShapeFeature> shape_;
    std::vector<OutlineSide> outline_;
    std::vector<PanelCutout> cutouts_;
};

} // namespace rc::core
